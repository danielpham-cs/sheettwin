def WEEKDAY(v, kind=1.0):
    x, kind = _arg_num(v), _arg_int(kind)
    e = first_error(x, kind)
    if e:
        return e
    n = int(math.floor(x))
    sunday0 = (n - 1) % 7 if n >= 1 else 6  # serial 1 (1900-01-01, as Excel has it) is a Sunday
    if kind == 1:
        return float(sunday0 + 1)
    if kind == 2:
        return float((sunday0 + 6) % 7 + 1)
    if kind == 3:
        return float((sunday0 + 6) % 7)
    return NUM


def EDATE(start, months):
    d, m = _date_of(start), _arg_int(months)
    e = first_error(d, m)
    if e:
        return e
    y, mo = divmod(d.month - 1 + m, 12)
    year, month = d.year + y, mo + 1
    import calendar
    day = min(d.day, calendar.monthrange(year, month)[1])
    return float(math.floor(date_serial(dt.datetime(year, month, day))))


def EOMONTH(start, months):
    d, m = _date_of(start), _arg_int(months)
    e = first_error(d, m)
    if e:
        return e
    y, mo = divmod(d.month - 1 + m, 12)
    year, month = d.year + y, mo + 1
    import calendar
    return float(date_serial(dt.datetime(year, month, calendar.monthrange(year, month)[1])))


def DAYS360(start, end, european=False):
    a, b = _date_of(start), _date_of(end)
    e = first_error(a, b)
    if e:
        return e
    d1, d2 = a.day, b.day
    if to_bool(scalar(european)) is True:
        d1, d2 = min(d1, 30), min(d2, 30)
    else:
        if d1 == 31:
            d1 = 30
        if d2 == 31 and d1 >= 30:
            d2 = 30
    return float((b.year - a.year) * 360 + (b.month - a.month) * 30 + (d2 - d1))


# ---------------------------------------------------------------- financial -----------------------------------------

def PMT(rate, nper, pv, fv=0.0, when=0.0):
    r, n, p, f, w = (_arg_num(x) for x in (rate, nper, pv, fv, when))
    e = first_error(r, n, p, f, w)
    if e:
        return e
    if n == 0:
        return NUM
    if r == 0:
        return -(p + f) / n
    t = (1 + r) ** n
    return -(r * (p * t + f)) / ((1 + r * (1 if w else 0)) * (t - 1))


def PV(rate, nper, pmt, fv=0.0, when=0.0):
    r, n, m, f, w = (_arg_num(x) for x in (rate, nper, pmt, fv, when))
    e = first_error(r, n, m, f, w)
    if e:
        return e
    if r == 0:
        return -(f + m * n)
    t = (1 + r) ** n
    return -(f + m * (1 + r * (1 if w else 0)) * (t - 1) / r) / t


def FV(rate, nper, pmt, pv=0.0, when=0.0):
    r, n, m, p, w = (_arg_num(x) for x in (rate, nper, pmt, pv, when))
    e = first_error(r, n, m, p, w)
    if e:
        return e
    if r == 0:
        return -(p + m * n)
    t = (1 + r) ** n
    return -(p * t + m * (1 + r * (1 if w else 0)) * (t - 1) / r)


def NPV(rate, *values):
    r = _arg_num(rate)
    xs = _numbers(values)
    e = first_error(r, xs)
    if e:
        return e
    if r == -1:
        return DIV0
    return math.fsum(v / (1 + r) ** (i + 1) for i, v in enumerate(xs))


def _solve(f, df, guess):
    x = guess
    for _ in range(100):
        y, d = f(x), df(x)
        if d == 0:
            return NUM
        nx = x - y / d
        if abs(nx - x) < 1e-10:
            return nx
        x = nx
        if x <= -1:
            return NUM
    return NUM


def IRR(values, guess=0.1):
    xs = _numbers([values])
    g = _arg_num(guess)
    e = first_error(xs, g)
    if e:
        return e
    if not (any(v > 0 for v in xs) and any(v < 0 for v in xs)):
        return NUM
    f = lambda r: math.fsum(v / (1 + r) ** i for i, v in enumerate(xs))  # noqa: E731
    df = lambda r: math.fsum(-i * v / (1 + r) ** (i + 1) for i, v in enumerate(xs))  # noqa: E731
    try:
        return _solve(f, df, g)
    except (OverflowError, ZeroDivisionError):
        return NUM


def _pairs(values, dates):
    vs, ds = _cells(values), _cells(dates)
    if len(vs) != len(ds):
        return NUM
    out = []
    for v, d in zip(vs, ds):
        if isinstance(v, XLError):
            return v
        if isinstance(d, XLError):
            return d
        if not isinstance(v, (int, float)) or not isinstance(d, (int, float)):
            return VALUE
        out.append((float(v), math.floor(float(d))))
    return out


def XNPV(rate, values, dates):
    r = _arg_num(rate)
    ps = _pairs(values, dates)
    e = first_error(r, ps)
    if e:
        return e
    if r <= -1:
        return NUM
    d0 = ps[0][1]
    return math.fsum(v / (1 + r) ** ((d - d0) / 365) for v, d in ps)


def XIRR(values, dates, guess=0.1):
    ps = _pairs(values, dates)
    g = _arg_num(guess)
    e = first_error(ps, g)
    if e:
        return e
    if not (any(v > 0 for v, _ in ps) and any(v < 0 for v, _ in ps)):
        return NUM
    d0 = ps[0][1]
    f = lambda r: math.fsum(v / (1 + r) ** ((d - d0) / 365) for v, d in ps)  # noqa: E731
    df = lambda r: math.fsum(-(d - d0) / 365 * v / (1 + r) ** ((d - d0) / 365 + 1) for v, d in ps)  # noqa: E731
    try:
        return _solve(f, df, g)
    except (OverflowError, ZeroDivisionError):
        return NUM


def _ipmt_ppmt(rate, per, nper, pv, fv, when):
    r, p, n, v, f, w = (_arg_num(x) for x in (rate, per, nper, pv, fv, when))
    e = first_error(r, p, n, v, f, w)
    if e:
        return e
    if not 1 <= p <= n:
        return NUM
    pmt = PMT(r, n, v, f, w)
    if isinstance(pmt, XLError):
        return pmt
    if w and p == 1:
        interest = 0.0
    else:
        # balance after per-1 payments, interest charged on it
        bal = -FV(r, p - 1, pmt, v, w)
        if w:
            bal -= pmt
        interest = -bal * r
    return interest, pmt


def IPMT(rate, per, nper, pv, fv=0.0, when=0.0):
    out = _ipmt_ppmt(rate, per, nper, pv, fv, when)
    return out if isinstance(out, XLError) else out[0]


def PPMT(rate, per, nper, pv, fv=0.0, when=0.0):
    out = _ipmt_ppmt(rate, per, nper, pv, fv, when)
    return out if isinstance(out, XLError) else out[1] - out[0]


def PERCENTILE(rng, k):
    xs = _numbers([rng])
    k = _arg_num(k)
    e = first_error(xs, k)
    if e:
        return e
    if not xs or not 0 <= k <= 1:
        return NUM
    xs.sort()
    h = (len(xs) - 1) * k
    lo = int(math.floor(h))
    return xs[lo] if lo + 1 >= len(xs) else xs[lo] + (h - lo) * (xs[lo + 1] - xs[lo])


def QUARTILE(rng, q):
    q = _arg_int(q)
    if isinstance(q, XLError):
        return q
    return NUM if not 0 <= q <= 4 else PERCENTILE(rng, q / 4)


def _numbers_a(args):
    """MAXA / MINA / AVERAGEA: text in a range counts as 0, logicals as 1 / 0."""
    out = []
    for a in args:
        if isinstance(a, Range):
            for v in a.values():
                if isinstance(v, XLError):
                    return v
                if v is None:
                    continue
                out.append(float(v) if isinstance(v, (int, float)) else 0.0)
        elif a is not None:
            x = to_number(a)
            if isinstance(x, XLError):
                return x
            out.append(x)
    return out


def MAXA(*args):
    xs = _numbers_a(args)
    return xs if isinstance(xs, XLError) else max(xs) if xs else 0.0


def MINA(*args):
    xs = _numbers_a(args)
    return xs if isinstance(xs, XLError) else min(xs) if xs else 0.0


def AVERAGEA(*args):
    xs = _numbers_a(args)
    if isinstance(xs, XLError):
        return xs
    return math.fsum(xs) / len(xs) if xs else DIV0


def RANK(x, rng, order=0.0):
    x, o = _arg_num(x), _arg_int(order)
    xs = _numbers([rng])
    e = first_error(x, o, xs)
    if e:
        return e
    if x not in xs:
        return NA
    return float(1 + sum(v > x for v in xs)) if o == 0 else float(1 + sum(v < x for v in xs))


