def DATE(y, m, d):
    y, m, d = _arg_int(y), _arg_int(m), _arg_int(d)
    e = first_error(y, m, d)
    if e:
        return e
    if 0 <= y < 1900:
        y += 1900
    y += (m - 1) // 12
    m = (m - 1) % 12 + 1
    try:
        base = dt.datetime(y, m, 1)
    except ValueError:
        return NUM
    serial = date_serial(base) + d - 1
    return NUM if serial < 0 else float(serial)


def _date_of(v):
    x = _arg_num(v)
    if isinstance(x, XLError):
        return x
    if x < 0:
        return NUM
    return serial_date(x)


