# ---------------------------------------------------------------- lookup --------------------------------------------

def _match_pos(value, keys: list, mode: int):
    """1-based position of `value` in `keys` (MATCH semantics; mode 0 exact with wildcards, 1 / -1 sorted)."""
    if isinstance(value, XLError):
        return value
    if mode == 0:
        if isinstance(value, str) and any(ch in value for ch in "*?"):
            pred = _criterion("=" + value)
            for i, k in enumerate(keys):
                if pred(k):
                    return i + 1
            return NA
        for i, k in enumerate(keys):
            if k is not None and not isinstance(k, XLError) and _rank(k) == _rank(value) and _compare(k, value) == 0:
                return i + 1
        return NA
    # approximate: binary search over values of the same type as `value`, like Excel
    lo, hi, best = 0, len(keys) - 1, None
    while lo <= hi:
        mid = (lo + hi) // 2
        k = keys[mid]
        if k is None or isinstance(k, XLError) or _rank(k) != _rank(value):
            # Excel skips mismatched types; a linear scan from here keeps the result well defined
            j = mid
            while j <= hi and (keys[j] is None or isinstance(keys[j], XLError) or _rank(keys[j]) != _rank(value)):
                j += 1
            if j > hi:
                hi = mid - 1
                continue
            mid, k = j, keys[j]
        c = _compare(k, value)
        if mode == 1:
            if c <= 0:
                best, lo = mid, mid + 1
            else:
                hi = mid - 1
        else:
            if c >= 0:
                best, lo = mid, mid + 1
            else:
                hi = mid - 1
    return NA if best is None else best + 1


def MATCH(value, rng, mode=1.0):
    value, mode = scalar(value), _arg_int(mode)
    e = first_error(value, mode)
    if e:
        return e
    if not isinstance(rng, Range) or (rng.height > 1 and rng.width > 1):
        return NA
    keys = list(rng.values())
    pos = _match_pos(value, keys, 0 if mode == 0 else (1 if mode > 0 else -1))
    return pos if isinstance(pos, XLError) else float(pos)


def VLOOKUP(value, table, col, exact=True):
    value = scalar(value)
    col = _arg_int(col)
    approx = to_bool(scalar(_thunk(exact)))
    e = first_error(value, col, approx)
    if e:
        return e
    if not isinstance(table, Range):
        return NA
    if col < 1:
        return VALUE
    if col > table.width:
        return REF
    keys = [row[0] for row in table.rows]
    pos = _match_pos(value, keys, 1 if approx else 0)
    if isinstance(pos, XLError):
        return pos
    v = table.rows[pos - 1][col - 1]
    return 0.0 if v is None else v


def HLOOKUP(value, table, row, exact=True):
    value = scalar(value)
    row = _arg_int(row)
    approx = to_bool(scalar(_thunk(exact)))
    e = first_error(value, row, approx)
    if e:
        return e
    if not isinstance(table, Range):
        return NA
    if row < 1:
        return VALUE
    if row > table.height:
        return REF
    pos = _match_pos(value, list(table.rows[0]), 1 if approx else 0)
    if isinstance(pos, XLError):
        return pos
    v = table.rows[row - 1][pos - 1]
    return 0.0 if v is None else v


def LOOKUP(value, keys, results=None):
    value = scalar(value)
    if isinstance(value, XLError):
        return value
    if not isinstance(keys, Range):
        return NA
    if results is None:
        if keys.height >= keys.width:
            ks, rs = [r[0] for r in keys.rows], [r[-1] for r in keys.rows]
        else:
            ks, rs = list(keys.rows[0]), list(keys.rows[-1])
    else:
        ks, rs = list(keys.values()), list(results.values()) if isinstance(results, Range) else [results]
    pos = _match_pos(value, ks, 1)
    if isinstance(pos, XLError):
        return pos
    return rs[pos - 1] if pos - 1 < len(rs) else NA


def INDEX(rng, row, col=None):
    row = _arg_int(row)
    col = _arg_int(col) if col is not None else None
    e = first_error(row, col)
    if e:
        return e
    if not isinstance(rng, Range):
        return rng if row in (0, 1) and col in (None, 0, 1) else REF
    if col is None:
        if rng.height == 1:
            row, col = 1, row
        else:
            col = 1 if rng.width == 1 else 0
    if row < 0 or col < 0 or row > rng.height or col > rng.width:
        return REF
    if row == 0 and col == 0:
        return rng
    if row == 0:
        return Range([[r[col - 1]] for r in rng.rows], rng.top, rng.left + col - 1)
    if col == 0:
        return Range([list(rng.rows[row - 1])], rng.top + row - 1, rng.left)
    v = rng.rows[row - 1][col - 1]
    return 0.0 if v is None else v


