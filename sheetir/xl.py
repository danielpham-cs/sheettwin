# ---------------------------------------------------------------- the workbook being computed -----------------------

class Model:
    """Values of a workbook computed from its constants by translated formula groups.

    `constants`: (sheet, row, col) -> value of every non-formula cell.
    `formulas`: (sheet, row, col) -> (function, baseline) for every formula cell; function is a translated group's
        function `fn(m, row, col)` or None (not translated: the cell keeps `baseline`, Excel's saved value).
    `extent`: sheet -> (max_row, max_col), to bound whole-column / whole-row references.
    `frozen`: when set, formula cells other than the one being computed read their baseline (V1's isolated mode:
        each group is checked on Excel's own inputs, so one wrong group cannot hide or cause another's mismatch).
    """

    def __init__(self, constants: dict, formulas: dict, extent: dict, frozen: bool = False):
        self.constants, self.formulas, self.extent, self.frozen = dict(constants), formulas, extent, frozen
        self.values: dict = {}
        self._ranges: dict = {}
        self._busy: set = set()
        self._active = None

    def set(self, cell, value) -> None:
        """Change a constant (a scenario input). Computed values are discarded."""
        self.constants[cell] = value
        self.values.clear()
        self._ranges.clear()

    def c(self, sheet: str, row: int, col: int):
        key = (sheet, row, col)
        if key in self.constants:
            return self.constants[key]
        f = self.formulas.get(key)
        if f is None:
            return None
        if self.frozen and key != self._active:
            return f[1]
        if key in self.values:
            return self.values[key]
        return self.compute(key)

    def r(self, sheet: str, r1, c1, r2, c2) -> Range:
        mr, mc = self.extent.get(sheet, (0, 0))
        if r1 is None:
            r1, r2 = 1, max(mr, 1)
        if c1 is None:
            c1, c2 = 1, max(mc, 1)
        r2, c2 = min(r2, max(mr, r1)), min(c2, max(mc, c1))  # nothing lies past the used area
        key = (sheet, r1, c1, r2, c2)
        hit = self._ranges.get(key)
        if hit is not None:
            return hit
        settled = True
        rows = []
        for r in range(r1, r2 + 1):
            row = []
            for c in range(c1, c2 + 1):
                k = (sheet, r, c)
                if k in self.constants:
                    row.append(self.constants[k])
                    continue
                f = self.formulas.get(k)
                if f is None:
                    row.append(None)
                elif self.frozen or f[0] is None:
                    row.append(f[1] if (self.frozen and k != self._active) or f[0] is None else self.c(sheet, r, c))
                    settled = settled and k != self._active
                else:
                    was = k in self.values
                    row.append(self.c(sheet, r, c))
                    settled = settled and (was or k in self.values)
            rows.append(row)
        rng = Range(rows, r1, c1)
        if settled:
            self._ranges[key] = rng
        return rng

    def compute(self, key):
        fn, baseline = self.formulas[key]
        if fn is None:
            return baseline
        if key in self._busy:
            return XLError("#CYCLE!")
        self._busy.add(key)
        outer, self._active = self._active, key
        try:
            v = fn(self, key[1], key[2])
            if isinstance(v, Range):
                v = scalar(v, key[1], key[2])
                if isinstance(v, Range):
                    v = VALUE
            if v is None:
                v = 0.0
            if isinstance(v, bool):
                pass
            elif isinstance(v, int):
                v = float(v)
        except Unsupported:
            v = XLError("#UNSUPPORTED!")
        except RecursionError:
            v = XLError("#DEPTH!")
        finally:
            self._busy.discard(key)
            self._active = outer
        if not self.frozen:
            self.values[key] = v
        return v

    def compute_all(self, order) -> dict:
        """Compute formula cells in `order` (precedents first, so the recursion stays shallow)."""
        out = {}
        for key in order:
            if self.frozen:
                self._active = key
                out[key] = self.compute(key)
                self._active = None
            else:
                out[key] = self.values[key] if key in self.values else self.compute(key)
        return out


def same(expected, got, rel: float = 1e-9, abs_: float = 1e-9) -> bool:
    """Equality as a check counts it: numbers within tolerance, text exactly, errors by code, blank as 0 or ""."""
    if isinstance(expected, XLError) or isinstance(got, XLError):
        return isinstance(expected, XLError) and isinstance(got, XLError) and str(expected) == str(got)
    if expected is None:
        expected = "" if isinstance(got, str) else 0.0
    if got is None:
        got = "" if isinstance(expected, str) else 0.0
    if isinstance(expected, bool) or isinstance(got, bool):
        return isinstance(expected, bool) and isinstance(got, bool) and expected == got
    if isinstance(expected, (int, float)) and isinstance(got, (int, float)):
        return math.isclose(float(expected), float(got), rel_tol=rel, abs_tol=abs_)
    if isinstance(expected, str) and isinstance(got, str):
        return expected == got
    return False
