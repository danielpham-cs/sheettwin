def SUBTOTAL(code, *refs):
    """SUBTOTAL without hidden rows (the twin has no notion of hidden rows) and without the rule that nested
    SUBTOTAL cells are skipped; V1 catches a workbook where either matters."""
    c = _arg_int(code)
    if isinstance(c, XLError):
        return c
    name = _SUBTOTAL.get(c % 100)
    if name is None:
        return VALUE
    return globals()[name](*refs)


def _holidays(h):
    if h is None:
        return set()
    return {math.floor(v) for v in _cells(h) if isinstance(v, (int, float)) and not isinstance(v, bool)}


def _is_workday(n: int, hol: set) -> bool:
    return WEEKDAY(float(n), 2.0) <= 5 and n not in hol


def WORKDAY(start, days, holidays=None):
    s, d = _arg_num(start), _arg_int(days)
    e = first_error(s, d)
    if e:
        return e
    n, hol, step = int(math.floor(s)), _holidays(holidays), 1 if d >= 0 else -1
    left = abs(d)
    while left:
        n += step
        if _is_workday(n, hol):
            left -= 1
    return float(n)


def NETWORKDAYS(start, end, holidays=None):
    s, t = _arg_num(start), _arg_num(end)
    e = first_error(s, t)
    if e:
        return e
    a, b = int(math.floor(s)), int(math.floor(t))
    hol = _holidays(holidays)
    sign = 1 if a <= b else -1
    lo, hi = min(a, b), max(a, b)
    return float(sign * sum(_is_workday(n, hol) for n in range(lo, hi + 1)))


