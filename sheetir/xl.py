"""Runtime for the Python twin: Excel value semantics, operators and worksheet functions.

Code generated by sheetir.transpile calls only what this module defines. Values follow Excel's rules:

    blank        None (0 in arithmetic, "" in text)
    number       float (int and bool are accepted, bool counts as 1/0 in arithmetic)
    text         str
    logical      bool
    error        XLError("#DIV/0!") etc.; an error operand makes the result that error
    range        Range: a rectangle of values, with its position so a single-cell range reads as that cell

Functions that a twin cannot evaluate here raise Unsupported at translation time, never at run time: the translator
only emits calls listed in FUNCTIONS.
"""

from __future__ import annotations

import datetime as dt
import math
import re
from decimal import ROUND_CEILING, ROUND_FLOOR, ROUND_HALF_UP, Decimal


# ---------------------------------------------------------------- values -------------------------------------------

class XLError(str):
    """An Excel error value. Compares equal to its code, so XLError("#N/A") == "#N/A"."""

    def __repr__(self) -> str:
        return f"XLError({str(self)!r})"


ERRORS = ("#NULL!", "#DIV/0!", "#VALUE!", "#REF!", "#NAME?", "#NUM!", "#N/A")
DIV0, VALUE, REF, NAME, NUM, NA = (XLError(e) for e in ("#DIV/0!", "#VALUE!", "#REF!", "#NAME?", "#NUM!", "#N/A"))


class Unsupported(Exception):
    """A formula uses something the twin cannot evaluate faithfully (raised by the translator, or by a function that
    meets an argument form it does not handle)."""


class Range:
    """Values of a rectangular block, row-major. `top`/`left` locate it, for implicit intersection."""

    __slots__ = ("rows", "top", "left")

    def __init__(self, rows: list[list], top: int = 1, left: int = 1):
        self.rows, self.top, self.left = rows, top, left

    @property
    def height(self) -> int:
        return len(self.rows)

    @property
    def width(self) -> int:
        return len(self.rows[0]) if self.rows else 0

    def values(self):
        for row in self.rows:
            yield from row

    def __repr__(self) -> str:
        return f"Range({self.rows!r})"


def is_error(v) -> bool:
    return isinstance(v, XLError)


def first_error(*vs):
    for v in vs:
        if isinstance(v, XLError):
            return v
    return None


def scalar(v, row: int | None = None, col: int | None = None):
    """A single value from an operand: a 1x1 range is its cell; a row or column range intersects the host's row/col
    (Excel's implicit intersection); anything else is #VALUE!."""
    if not isinstance(v, Range):
        return v
    if v.height == 1 and v.width == 1:
        return v.rows[0][0]
    if v.width == 1 and row is not None and v.top <= row < v.top + v.height:
        return v.rows[row - v.top][0]
    if v.height == 1 and col is not None and v.left <= col < v.left + v.width:
        return v.rows[0][col - v.left]
    return VALUE


_NUM_TEXT = re.compile(r"^\s*[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?\s*%?\s*$")


def to_number(v):
    """Coerce for arithmetic: blank 0, bool 1/0, numeric text its number, other text #VALUE!."""
    if v is None:
        return 0.0
    if isinstance(v, bool):
        return 1.0 if v else 0.0
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, XLError):
        return v
    if isinstance(v, str):
        t = v.strip().replace(",", "")
        if _NUM_TEXT.match(t):
            if t.endswith("%"):
                return float(t[:-1]) / 100
            return float(t)
        return VALUE
    if isinstance(v, (dt.datetime, dt.date)):
        return date_serial(v)
    return VALUE


def to_text(v) -> str | XLError:
    if v is None:
        return ""
    if isinstance(v, XLError):
        return v
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, float):
        return fmt_general(v)
    return str(v)


def fmt_general(x: float) -> str:
    """Excel's General format for a number in text context (=1/4&"" gives 0.25, =10&"" gives 10)."""
    if x == int(x) and abs(x) < 1e15:
        return str(int(x))
    s = f"{x:.15g}"
    if "e" in s:
        mant, exp = s.split("e")
        return f"{mant}E{int(exp):+03d}"
    return s


def to_bool(v):
    if isinstance(v, XLError):
        return v
    if v is None:
        return False
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return v != 0
    if isinstance(v, str):
        if v.upper() == "TRUE":
            return True
        if v.upper() == "FALSE":
            return False
        return VALUE
    return VALUE


_EPOCH = dt.datetime(1899, 12, 30)


def date_serial(d) -> float:
    if isinstance(d, dt.datetime):
        delta = d - _EPOCH
    elif isinstance(d, dt.date):
        delta = dt.datetime(d.year, d.month, d.day) - _EPOCH
    elif isinstance(d, dt.time):
        return (d.hour * 3600 + d.minute * 60 + d.second + d.microsecond / 1e6) / 86400
    else:
        raise TypeError(d)
    serial = delta.days + delta.seconds / 86400 + delta.microseconds / 86400e6
    return float(serial if serial >= 61 else serial - 1 if serial >= 1 else serial)  # Excel's 1900-02-29


def serial_date(n: float) -> dt.datetime:
    n = float(n)
    if n < 61:
        n += 1
    return _EPOCH + dt.timedelta(days=n)


# ---------------------------------------------------------------- element-wise operators -----------------------------

def _lift(fn):
    """Apply a scalar operator element-wise when an operand is a range (array arithmetic, as inside SUMPRODUCT)."""

    def op(a, b):
        if isinstance(a, Range) or isinstance(b, Range):
            ra = a if isinstance(a, Range) else None
            rb = b if isinstance(b, Range) else None
            h = max(ra.height if ra else 1, rb.height if rb else 1)
            w = max(ra.width if ra else 1, rb.width if rb else 1)

            def at(x, rx, i, j):
                if rx is None:
                    return x
                ii = 0 if rx.height == 1 else i
                jj = 0 if rx.width == 1 else j
                if ii >= rx.height or jj >= rx.width:
                    return NA
                return rx.rows[ii][jj]

            return Range([[fn(at(a, ra, i, j), at(b, rb, i, j)) for j in range(w)] for i in range(h)],
                         ra.top if ra else rb.top, ra.left if ra else rb.left)
        return fn(a, b)

    return op


def _arith(f):
    def fn(a, b):
        x, y = to_number(a), to_number(b)
        e = first_error(x, y)
        if e:
            return e
        try:
            r = f(x, y)
        except ZeroDivisionError:
            return DIV0
        except (OverflowError, ValueError):
            return NUM
        if isinstance(r, complex) or (isinstance(r, float) and (math.isnan(r) or math.isinf(r))):
            return NUM
        return r

    return _lift(fn)


def _pow(x, y):
    if x == 0 and y == 0:
        raise ValueError
    if x == 0 and y < 0:
        raise ZeroDivisionError
    return x ** y


def _snap(r: float, x: float, y: float) -> float:
    """Excel returns exactly 0 when + or - cancels to within rounding noise of its operands (=0.3-0.2-0.1 is 0)."""
    if r != 0 and abs(r) <= max(abs(x), abs(y)) * 2.0 ** -49:
        return 0.0
    return r


add = _arith(lambda x, y: _snap(x + y, x, y))
sub = _arith(lambda x, y: _snap(x - y, x, y))
mul = _arith(lambda x, y: x * y)
div = _arith(lambda x, y: x / y)
power = _arith(_pow)


def neg(a):
    if isinstance(a, Range):
        return Range([[neg(v) for v in row] for row in a.rows], a.top, a.left)
    x = to_number(a)
    return x if isinstance(x, XLError) else -x


def pos(a):
    return a


def percent(a):
    if isinstance(a, Range):
        return Range([[percent(v) for v in row] for row in a.rows], a.top, a.left)
    x = to_number(a)
    return x if isinstance(x, XLError) else x / 100


@_lift
def concat(a, b):
    x, y = to_text(a), to_text(b)
    return first_error(x, y) or x + y


def _rank(v):
    """Excel's cross-type order: numbers < text < logicals; blank compares as 0 or "" to whatever it meets."""
    if isinstance(v, bool):
        return 2
    if isinstance(v, str):
        return 1
    return 0


def _compare(a, b) -> int | XLError:
    e = first_error(a, b)
    if e:
        return e
    if a is None:
        a = "" if isinstance(b, str) else False if isinstance(b, bool) else 0.0
    if b is None:
        b = "" if isinstance(a, str) else False if isinstance(a, bool) else 0.0
    ra, rb = _rank(a), _rank(b)
    if ra != rb:
        return -1 if ra < rb else 1
    if ra == 1:
        a, b = a.lower(), b.lower()
    elif ra == 0:
        a, b = float(a), float(b)
    return (a > b) - (a < b)


def _cmp(test):
    def fn(a, b):
        c = _compare(a, b)
        return c if isinstance(c, XLError) else test(c)

    return _lift(fn)


eq = _cmp(lambda c: c == 0)
ne = _cmp(lambda c: c != 0)
lt = _cmp(lambda c: c < 0)
le = _cmp(lambda c: c <= 0)
gt = _cmp(lambda c: c > 0)
ge = _cmp(lambda c: c >= 0)


# ---------------------------------------------------------------- argument helpers ----------------------------------

def _flatten(args, *, ranges_only_numbers: bool = True):
    """Values for an aggregate: a range contributes only its numbers (text, logicals, blanks skipped); a direct
    argument is coerced (TRUE counts as 1, numeric text as its number). Errors anywhere are returned as-is."""
    for a in args:
        if isinstance(a, Range):
            for v in a.values():
                if isinstance(v, XLError):
                    yield v
                elif isinstance(v, (int, float)) and not isinstance(v, bool):
                    yield float(v)
                elif not ranges_only_numbers and v is not None:
                    yield v
        elif a is None:
            continue
        else:
            x = to_number(a)
            yield x


def _numbers(args):
    out = []
    for v in _flatten(args):
        if isinstance(v, XLError):
            return v
        out.append(v)
    return out


def _arg_num(v):
    v = scalar(v)
    return to_number(v)


def _arg_int(v):
    x = _arg_num(v)
    return x if isinstance(x, XLError) else int(math.floor(x)) if x >= 0 else int(math.ceil(x))


def _thunk(v):
    return v() if callable(v) else v


# ---------------------------------------------------------------- math & aggregates ---------------------------------

def SUM(*args):
    xs = _numbers(args)
    return xs if isinstance(xs, XLError) else math.fsum(xs)


def PRODUCT(*args):
    xs = _numbers(args)
    return xs if isinstance(xs, XLError) else math.prod(xs) if xs else 0.0


def AVERAGE(*args):
    xs = _numbers(args)
    if isinstance(xs, XLError):
        return xs
    return math.fsum(xs) / len(xs) if xs else DIV0


def MIN(*args):
    xs = _numbers(args)
    return xs if isinstance(xs, XLError) else min(xs) if xs else 0.0


def MAX(*args):
    xs = _numbers(args)
    return xs if isinstance(xs, XLError) else max(xs) if xs else 0.0


def COUNT(*args):
    n = 0
    for a in args:
        if isinstance(a, Range):
            n += sum(isinstance(v, (int, float)) and not isinstance(v, bool) for v in a.values())
        elif not isinstance(to_number(a), XLError) and a is not None:
            n += 1
    return float(n)


def COUNTA(*args):
    n = 0
    for a in args:
        if isinstance(a, Range):
            n += sum(v is not None and v != "" for v in a.values())
        else:
            n += 1
    return float(n)


def COUNTBLANK(rng):
    if not isinstance(rng, Range):
        return VALUE
    return float(sum(v is None or v == "" for v in rng.values()))


def MEDIAN(*args):
    xs = _numbers(args)
    if isinstance(xs, XLError):
        return xs
    if not xs:
        return NUM
    xs.sort()
    m = len(xs) // 2
    return xs[m] if len(xs) % 2 else (xs[m - 1] + xs[m]) / 2


def _stdev(args, sample: bool):
    xs = _numbers(args)
    if isinstance(xs, XLError):
        return xs
    n = len(xs)
    if n < (2 if sample else 1):
        return DIV0
    mean = math.fsum(xs) / n
    return math.sqrt(math.fsum((x - mean) ** 2 for x in xs) / (n - 1 if sample else n))


def STDEV(*args):
    return _stdev(args, True)


def STDEVP(*args):
    return _stdev(args, False)


def LARGE(rng, k):
    xs = _numbers([rng])
    k = _arg_int(k)
    e = first_error(xs, k)
    if e:
        return e
    if not 1 <= k <= len(xs):
        return NUM
    return sorted(xs, reverse=True)[k - 1]


def SMALL(rng, k):
    xs = _numbers([rng])
    k = _arg_int(k)
    e = first_error(xs, k)
    if e:
        return e
    if not 1 <= k <= len(xs):
        return NUM
    return sorted(xs)[k - 1]


def SUMSQ(*args):
    xs = _numbers(args)
    return xs if isinstance(xs, XLError) else math.fsum(x * x for x in xs)


def _round(x, digits, mode):
    x, digits = _arg_num(x), _arg_int(digits)
    e = first_error(x, digits)
    if e:
        return e
    d = Decimal(f"{float(x):.15g}")  # Excel rounds what it would display at 15 significant digits
    q = Decimal(1).scaleb(-digits)
    if mode == "half":
        r = d.quantize(q, rounding=ROUND_HALF_UP) if digits >= 0 else (d / q).quantize(1, ROUND_HALF_UP) * q
    elif mode == "up":  # away from zero
        rnd = ROUND_CEILING if d >= 0 else ROUND_FLOOR
        r = d.quantize(q, rounding=rnd) if digits >= 0 else (d / q).quantize(1, rnd) * q
    else:  # down: toward zero
        rnd = ROUND_FLOOR if d >= 0 else ROUND_CEILING
        r = d.quantize(q, rounding=rnd) if digits >= 0 else (d / q).quantize(1, rnd) * q
    return float(r)


def ROUND(x, digits=0.0):
    return _round(x, digits, "half")


def ROUNDUP(x, digits=0.0):
    return _round(x, digits, "up")


def ROUNDDOWN(x, digits=0.0):
    return _round(x, digits, "down")


def TRUNC(x, digits=0.0):
    return _round(x, digits, "down")


def INT(x):
    x = _arg_num(x)
    return x if isinstance(x, XLError) else float(math.floor(x))


def ABS(x):
    x = _arg_num(x)
    return x if isinstance(x, XLError) else abs(x)


def SIGN(x):
    x = _arg_num(x)
    return x if isinstance(x, XLError) else float((x > 0) - (x < 0))


def MOD(x, y):
    x, y = _arg_num(x), _arg_num(y)
    e = first_error(x, y)
    if e:
        return e
    if y == 0:
        return DIV0
    return x - y * math.floor(x / y)


def POWER(x, y):
    return power(scalar(x), scalar(y))


def SQRT(x):
    x = _arg_num(x)
    if isinstance(x, XLError):
        return x
    return NUM if x < 0 else math.sqrt(x)


def EXP(x):
    x = _arg_num(x)
    if isinstance(x, XLError):
        return x
    try:
        return math.exp(x)
    except OverflowError:
        return NUM


def LN(x):
    x = _arg_num(x)
    if isinstance(x, XLError):
        return x
    return NUM if x <= 0 else math.log(x)


def LOG10(x):
    x = _arg_num(x)
    if isinstance(x, XLError):
        return x
    return NUM if x <= 0 else math.log10(x)


def LOG(x, base=10.0):
    x, base = _arg_num(x), _arg_num(base)
    e = first_error(x, base)
    if e:
        return e
    if x <= 0 or base <= 0:
        return NUM
    if base == 1:
        return DIV0
    return math.log(x) / math.log(base)


def PI():
    return math.pi


def CEILING(x, sig=1.0):
    x, sig = _arg_num(x), _arg_num(sig)
    e = first_error(x, sig)
    if e:
        return e
    if sig == 0:
        return 0.0
    if x > 0 and sig < 0:
        return NUM
    return math.ceil(x / sig) * sig


def FLOOR(x, sig=1.0):
    x, sig = _arg_num(x), _arg_num(sig)
    e = first_error(x, sig)
    if e:
        return e
    if sig == 0:
        return DIV0
    if x > 0 and sig < 0:
        return NUM
    return math.floor(x / sig) * sig


def SUMPRODUCT(*arrays):
    rs = []
    for a in arrays:
        if not isinstance(a, Range):
            a = Range([[a]])
        rs.append(a)
    h, w = rs[0].height, rs[0].width
    if any(r.height != h or r.width != w for r in rs):
        return VALUE
    total = 0.0
    for i in range(h):
        for j in range(w):
            p = 1.0
            for r in rs:
                v = r.rows[i][j]
                if isinstance(v, XLError):
                    return v
                p *= float(v) if isinstance(v, (int, float)) and not isinstance(v, bool) else 0.0
            total += p
    return total


# ---------------------------------------------------------------- criteria (SUMIF, COUNTIF, …) ----------------------

_CRIT = re.compile(r"^(<=|>=|<>|<|>|=)?(.*)$", re.S)


def _criterion(c):
    """A predicate for a SUMIF-style criterion: 5, ">5", "<>x", "a*", "" (blank)."""
    c = scalar(c)
    if isinstance(c, XLError):
        return c
    if c is None:
        c = 0.0
    if not isinstance(c, str):
        target = c

        def same(v):
            return not isinstance(v, XLError) and _compare(v, target) == 0 if v is not None else False

        return same
    op, operand = _CRIT.match(c).groups()
    op = op or "="
    num = to_number(operand) if operand != "" else None
    if operand == "":
        if op == "=":
            return lambda v: v is None or v == ""
        if op == "<>":
            return lambda v: not (v is None or v == "")
    if num is not None and not isinstance(num, XLError):
        def numeric(v):
            if isinstance(v, bool) or not isinstance(v, (int, float)):
                return op == "<>"
            c2 = (v > num) - (v < num)
            return {"=": c2 == 0, "<>": c2 != 0, "<": c2 < 0, "<=": c2 <= 0, ">": c2 > 0, ">=": c2 >= 0}[op]

        return numeric
    if op in ("=", "<>") and any(ch in operand for ch in "*?"):
        pat = re.compile("^" + re.escape(operand).replace(r"\*", ".*").replace(r"\?", ".").replace("~.*", r"\*")
                         + "$", re.I | re.S)

        def wild(v):
            hit = isinstance(v, str) and bool(pat.match(v))
            return hit if op == "=" else not hit

        return wild
    low = operand.lower()

    def text(v):
        if op in ("=", "<>"):
            hit = isinstance(v, str) and v.lower() == low
            return hit if op == "=" else not hit
        if not isinstance(v, str):
            return False
        c2 = (v.lower() > low) - (v.lower() < low)
        return {"<": c2 < 0, "<=": c2 <= 0, ">": c2 > 0, ">=": c2 >= 0}[op]

    return text


def _cells(r):
    return list(r.values()) if isinstance(r, Range) else [r]


def _ifs(pairs, target=None):
    """Matching positions for criteria pairs (range, criterion), and the values of `target` at those positions."""
    sizes = {len(_cells(r)) for r, _ in pairs}
    if target is not None:
        sizes.add(len(_cells(target)))
    if len(sizes) > 1:
        return VALUE
    preds = []
    for r, c in pairs:
        p = _criterion(c)
        if isinstance(p, XLError):
            return p
        preds.append((_cells(r), p))
    n = sizes.pop()
    hits = [i for i in range(n) if all(p(vals[i]) for vals, p in preds)]
    return hits


def SUMIF(rng, crit, sum_range=None):
    target = rng if sum_range is None else _resize(sum_range, rng)
    hits = _ifs([(rng, crit)], target)
    if isinstance(hits, XLError):
        return hits
    vals = _cells(target)
    total = 0.0
    for i in hits:
        v = vals[i]
        if isinstance(v, XLError):
            return v
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            total += v
    return total


def _resize(sum_range, like):
    """SUMIF's sum_range takes the shape of the criteria range, from its own top-left cell."""
    if isinstance(sum_range, Range) and isinstance(like, Range) and (
            sum_range.height, sum_range.width) != (like.height, like.width):
        raise Unsupported("SUMIF sum_range of a different size")
    return sum_range


def SUMIFS(sum_range, *pairs):
    ps = list(zip(pairs[::2], pairs[1::2]))
    hits = _ifs(ps, sum_range)
    if isinstance(hits, XLError):
        return hits
    vals = _cells(sum_range)
    total = 0.0
    for i in hits:
        v = vals[i]
        if isinstance(v, XLError):
            return v
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            total += v
    return total


def COUNTIF(rng, crit):
    hits = _ifs([(rng, crit)])
    return hits if isinstance(hits, XLError) else float(len(hits))


def COUNTIFS(*pairs):
    hits = _ifs(list(zip(pairs[::2], pairs[1::2])))
    return hits if isinstance(hits, XLError) else float(len(hits))


def AVERAGEIF(rng, crit, avg_range=None):
    target = rng if avg_range is None else _resize(avg_range, rng)
    hits = _ifs([(rng, crit)], target)
    if isinstance(hits, XLError):
        return hits
    vals = [v for i, v in enumerate(_cells(target)) if i in set(hits)
            and isinstance(v, (int, float)) and not isinstance(v, bool)]
    return math.fsum(vals) / len(vals) if vals else DIV0


def AVERAGEIFS(avg_range, *pairs):
    hits = _ifs(list(zip(pairs[::2], pairs[1::2])), avg_range)
    if isinstance(hits, XLError):
        return hits
    cells = _cells(avg_range)
    vals = [cells[i] for i in hits if isinstance(cells[i], (int, float)) and not isinstance(cells[i], bool)]
    return math.fsum(vals) / len(vals) if vals else DIV0


# ---------------------------------------------------------------- logical -------------------------------------------

def IF(cond, then=True, otherwise=False):
    c = to_bool(scalar(cond))
    if isinstance(c, XLError):
        return c
    v = _thunk(then) if c else _thunk(otherwise)
    return 0.0 if v is None else v


def IFERROR(value, fallback):
    v = _thunk(value)
    return _thunk(fallback) if isinstance(scalar(v), XLError) else v


def IFNA(value, fallback):
    v = _thunk(value)
    return _thunk(fallback) if scalar(v) == NA and isinstance(scalar(v), XLError) else v


def _logicals(args):
    out = []
    for a in args:
        if isinstance(a, Range):
            for v in a.values():
                if isinstance(v, XLError):
                    return v
                if isinstance(v, (bool, int, float)):
                    out.append(bool(v))
        else:
            b = to_bool(a)
            if isinstance(b, XLError):
                return b
            out.append(b)
    return out if out else VALUE


def AND(*args):
    xs = _logicals(args)
    return xs if isinstance(xs, XLError) else all(xs)


def OR(*args):
    xs = _logicals(args)
    return xs if isinstance(xs, XLError) else any(xs)


def NOT(v):
    b = to_bool(scalar(v))
    return b if isinstance(b, XLError) else not b


def TRUE():
    return True


def FALSE():
    return False


def ISBLANK(v):
    return scalar(v) is None


