def SUBSTITUTE(v, old, new, which=None):
    t, o, n = _text_arg(v), _text_arg(old), _text_arg(new)
    e = first_error(t, o, n)
    if e:
        return e
    if which is None:
        return t.replace(o, n) if o else t
    k = _arg_int(which)
    if isinstance(k, XLError):
        return k
    if k < 1:
        return VALUE
    idx = -1
    for _ in range(k):
        idx = t.find(o, idx + 1)
        if idx < 0:
            return t
    return t[:idx] + n + t[idx + len(o):]


