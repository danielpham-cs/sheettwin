def _find(needle, hay, start, ci):
    n, h, s = _text_arg(needle), _text_arg(hay), _arg_int(start)
    e = first_error(n, h, s)
    if e:
        return e
    if s < 1 or s > len(h) + 1:
        return VALUE
    if ci:
        if any(ch in n for ch in "*?"):
            pat = re.escape(n).replace(r"\*", ".*").replace(r"\?", ".")
            m = re.compile(pat, re.I | re.S).search(h, s - 1)
            return float(m.start() + 1) if m else VALUE
        i = h.lower().find(n.lower(), s - 1)
    else:
        i = h.find(n, s - 1)
    return VALUE if i < 0 else float(i + 1)


